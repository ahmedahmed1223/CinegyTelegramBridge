#requires -Version 7
<#
    Dot-sourced by TelegramBridge.ps1. NOT a module: these functions must
    share the bridge script's scope and $script: state.

    The manual in English, chapter for chapter with Bridge.Help.ps1.

    WHY THIS IS A SECOND FILE AND NOT CATALOGUE ENTRIES

    Everything else the bridge says goes through the catalogue in
    Modules/BridgeLanguage.psm1, one key per piece of text, precisely so the
    two languages sit together and a half-finished entry is a fact a test can
    state. The manual does not fit that shape:

      - a chapter is forty lines of prose, not a label, and forty lines in one
        catalogue value is not a string anybody can read or review; and
      - several chapters interpolate live settings mid-sentence, and the
        number lands in a different place in an English sentence than in an
        Arabic one. A {0} placeholder can move, but the surrounding clauses
        have to move with it, which is a rewrite rather than a substitution.

    So the structure is duplicated and the DRIFT IS GUARDED INSTEAD: a test in
    Bridge.Help.Tests.ps1 requires both languages to define exactly the same
    chapter keys, with the same AdminOnly flag, and a non-empty title and body
    for each. A chapter added to one language and not the other fails the gate
    by name. That is the trade this file makes, deliberately and once.
#>

