        @{ Key = 'back'; Title = '↩️ Going back and cancelling'; AdminOnly = $false; Body = @(
                '• ⬅️ Back at the bottom of every screen goes one step back.'
                '• 🏠 Menu returns you to the main screen at any time, even mid-typing.'
