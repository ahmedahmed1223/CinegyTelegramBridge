    if ($isAdmin) {
        $sheet = @($chapters | Where-Object { $_.Key -eq 'sheet' })[0]
        $sheet.Body += @(
            ''
            '⚙️ Setting it up (administrator):'
            '↳ "Google Sheets link (CSV)" in ⚙️ Settings: the CSV export link, not the'
