                '   requester sent.'
                '↳ Every approval is reported to all administrators with the name of whoever granted it.'
                '↳ ❌ Reject removes the request and blocks the chat so it can never ask'
                '   again. Turn off "block a rejected requester" for rejection without a block.'
                ''
                '📜 Past requests (a button on the requests screen): who asked, the state'
                '   (approved, rejected or awaiting a decision), when it was decided, by'
                '   whom, and how long they waited.'
